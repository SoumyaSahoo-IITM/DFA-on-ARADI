def fmt(lst) -> str:
    return ", ".join(str(v) for v in lst)


def write(name: str, text: str) -> None:
    os.makedirs(TAB, exist_ok=True)
    with open(os.path.join(TAB, name), "w") as f:
        f.write(text)


def md_table(header: Sequence[str], rows: Sequence[Sequence], align: str | None = None) -> str:
    out = ["| " + " | ".join(header) + " |"]
    out.append("|" + "|".join((":--" if (align is None or a == "l") else "--:") for a in (align or "l" * len(header))) + "|")
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out) + "\n"


def tex_esc(c) -> str:
    return str(c).replace("%", "\\%")


def tex_table(header: Sequence[str], rows: Sequence[Sequence], caption: str, label: str,
              colspec: str, star: bool = False, small: bool = True) -> str:
    env = "table"   # single-column document: no table*
    header = [tex_esc(h) for h in header]
    body = "\n".join(" & ".join(tex_esc(c) for c in r) + r" \\" for r in rows)
    tab = (f"\\begin{{tabular}}{{{colspec}}}\n\\toprule\n" + " & ".join(header) + r" \\" + "\n\\midrule\n"
           + body + "\n\\bottomrule\n\\end{tabular}")
    if star:
        tab = "\\resizebox{\\textwidth}{!}{" + tab + "}"
    return (f"\\begin{{{env}}}[H]\n\\centering\n\\caption{{{caption}}}\n\\label{{{label}}}\n"
            + ("\\small\n" if small else "") + tab + "\n" + f"\\end{{{env}}}\n")


def csv_write(name: str, header: Sequence[str], rows: Sequence[Sequence]) -> None:
    with open(os.path.join(TAB, name), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        for r in rows:
            w.writerow(r)


def section(title: str, level: int = 2) -> None:
    MD.append("\n" + "#" * level + " " + title + "\n")
    TEX.append("\n" + ("\\section" if level == 2 else "\\subsection") + "{" + title.replace("&", r"\&") + "}\n")


def para(md: str, tex: str | None = None) -> None:
    MD.append(md + "\n")
    TEX.append((tex if tex is not None else md) + "\n")


ALL_FORMATS = False   # set by --all-formats: also write every table as .md and .tex


def both(name: str, header, rows, caption, colspec, star=False, align=None, md_header=None):
    """Emit a table in the markdown and latex documents and as a CSV file
    (plus .md/.tex files when ALL_FORMATS is set)."""
    md = md_table(md_header or header, rows, align)
    tx = tex_table(header, rows, caption, "tab:" + name, colspec, star)
    if ALL_FORMATS:
        write(name + ".md", md)
        write(name + ".tex", tx)
    csv_write(name + ".csv", [h.replace("$", "") for h in (md_header or header)], rows)
    MD.append(f"**Table: {caption}**\n\n" + md)
    TEX.append(tx)


